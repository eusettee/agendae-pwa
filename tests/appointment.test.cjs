const test = require('node:test');
const assert = require('node:assert/strict');
process.env.SQLITE_PATH = ':memory:';
const { validateAppointment } = require('../lib/appointment.cjs');
const server = require('../server.cjs');
const valid = { patient: 'Paciente Demo', clinicId: 'boa-vista', professionalId: 'ana', date: '2099-10-05', time: '09:00' };
test('validação rejeita passado, fim de semana, datas inválidas e vínculo incorreto', () => {
  assert.equal(validateAppointment(valid, 0), null);
  assert.match(validateAppointment({ ...valid, date: '2020-10-05' }), /futuro/);
  assert.match(validateAppointment({ ...valid, date: '2099-10-03' }, 0), /segunda/);
  assert.match(validateAppointment({ ...valid, date: '2099-02-30' }, 0), /válida/);
  assert.match(validateAppointment({ ...valid, professionalId: 'julia' }, 0), /profissional/);
  assert.match(validateAppointment({ ...valid, patient: ' ' }), /nome/);
});
test('API responde ao catálogo, valida consulta e rejeita entradas inválidas', async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const response = await fetch(`${base}/api/catalog`);
    assert.equal(response.status, 200);
    assert.equal((await response.json()).clinics.length, 3);
    const register = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'register', name: 'Paciente Demo', email: 'demo@example.test', password: 'senha-teste-123', consent: true }) });
    assert.equal(register.status, 201);
    const cookie = register.headers.get('set-cookie').split(';')[0];
    assert.match(register.headers.get('set-cookie'), /HttpOnly/);
    const request = (method, data, auth = cookie) => fetch(`${base}/api/appointments`, { method, headers: { 'Content-Type': 'application/json', Cookie: auth }, body: data ? JSON.stringify(data) : undefined });
    assert.equal((await request('POST', valid, '')).status, 401);
    const success = await request('POST', valid);
    assert.equal(success.status, 201);
    const appointment = (await success.json()).appointment;
    assert.equal((await request('POST', valid)).status, 409);
    assert.equal((await request('POST', {})).status, 422);
    assert.equal((await fetch(`${base}/api/appointments`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' } })).status, 405);
    const other = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 'register', name: 'Outro Paciente', email: 'other@example.test', password: 'senha-teste-123', consent: true }) });
    const otherCookie = other.headers.get('set-cookie').split(';')[0];
    assert.equal((await (await request('GET', null, otherCookie)).json()).appointments.length, 0);
    assert.equal((await request('PUT', { ...valid, id: appointment.id }, otherCookie)).status, 404);
    assert.equal((await request('DELETE', { id: appointment.id }, otherCookie)).status, 404);
    assert.equal((await request('PUT', { ...valid, id: appointment.id, time: '10:00' })).status, 200);
    assert.equal((await request('DELETE', { id: appointment.id })).status, 200);
    assert.equal((await (await request('GET')).json()).appointments.length, 0);
    assert.equal((await request('POST', valid)).status, 201);
    const logout = await fetch(`${base}/api/auth`, { method: 'POST', headers: { 'Content-Type': 'application/json', Cookie: cookie }, body: JSON.stringify({ action: 'logout' }) });
    assert.equal(logout.status, 200);
    assert.equal((await request('GET')).status, 401);
    assert.equal((await fetch(`${base}/api/appointments`, { method: 'POST', body: 'invalid' })).status, 400);
    const manifest = await (await fetch(`${base}/manifest.json`)).json();
    assert.equal(manifest.display, 'standalone');
    for (const icon of manifest.icons) assert.equal((await fetch(base + icon.src)).status, 200);
  } finally { await new Promise(resolve => server.close(resolve)); }
});
