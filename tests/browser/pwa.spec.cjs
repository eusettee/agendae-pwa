const { test, expect, chromium } = require('@playwright/test');
test('agendamento persiste, bloqueia duplicidade e cancela offline após recarregar', async ({ page, context }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('link', { name: 'Ajuda', exact: true }).click();
  await expect(page.locator('#offline-ready')).toHaveText('Modo offline pronto');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await page.getByRole('link', { name: 'Agendar', exact: true }).click();
  await page.getByLabel('Como podemos chamar você?').fill('Paciente Demo');
  await page.getByLabel('09:00', { exact: true }).check();
  await page.getByLabel('Concordo em salvar').check();
  await page.getByRole('button', { name: /Salvar consulta/ }).click();
  await expect(page.locator('#appointment-list')).toContainText('Paciente Demo');
  await page.getByRole('link', { name: 'Agendar', exact: true }).click();
  await expect(page.getByLabel('09:00', { exact: true })).toBeDisabled();
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator('#connection')).toHaveText('Offline');
  await page.getByRole('link', { name: 'Consultas', exact: true }).click();
  await expect(page.locator('#appointment-list')).toContainText('Paciente Demo');
  await page.getByRole('button', { name: /Cancelar consulta de/ }).click();
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await expect(page.locator('#appointment-list')).toContainText('Sua agenda está livre');
  await page.getByRole('link', { name: 'Agendar', exact: true }).click();
  await expect(page.getByLabel('09:00', { exact: true })).toBeEnabled();
  await page.getByLabel('Como podemos chamar você?').fill('Demo Offline');
  await page.getByLabel('09:00', { exact: true }).check();
  await page.getByLabel('Concordo em salvar').check();
  await page.getByRole('button', { name: /Salvar consulta/ }).click();
  await page.reload();
  await expect(page.locator('#appointment-list')).toContainText('Demo Offline');
  expect(errors).toEqual([]);
});
test('manifest, cache, instalação oferecida e layouts desktop e celular', async ({ page }) => {
  let offered = false;
  await page.addInitScript(() => window.addEventListener('beforeinstallprompt', () => { window.installOffered = true; }));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  const manifest = await page.evaluate(async () => (await fetch('/manifest.json')).json());
  expect(manifest.icons.some(icon => icon.sizes === '192x192')).toBeTruthy();
  expect(manifest.icons.some(icon => icon.sizes === '512x512')).toBeTruthy();
  expect(manifest.display).toBe('standalone');
  const cached = await page.evaluate(async () => (await (await caches.open('agendae-v1')).keys()).map(request => new URL(request.url).pathname));
  expect(cached).toContain('/index.html'); expect(cached).toContain('/css/style.css'); expect(cached).toContain('/js/app.js');
  const session = await page.context().newCDPSession(page);
  await session.send('Page.enable');
  const eligibility = await session.send('Page.getInstallabilityErrors');
  expect(eligibility.installabilityErrors.filter(error => error.errorId !== 'in-incognito')).toEqual([]);
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Agendar', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'artifacts/mobile-agendar.png', fullPage: true });
  offered = await page.evaluate(() => Boolean(window.installOffered));
  console.log('Instalação oferecida pelo Chrome:', offered);
});
test('Chrome com perfil normal reconhece a PWA como instalável', async () => {
  const context = await chromium.launchPersistentContext('.test-browser', { channel: 'chrome', headless: true });
  try {
    const page = context.pages()[0];
    await page.goto('http://localhost:3000');
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload();
    const session = await context.newCDPSession(page);
    await session.send('Page.enable');
    const result = await session.send('Page.getInstallabilityErrors');
    expect(result.installabilityErrors).toEqual([]);
    console.log('PWA instalável: nenhum erro de elegibilidade no Chrome.');
  } finally { await context.close(); }
});
